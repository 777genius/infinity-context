def _imports(tree: ast.AST) -> tuple[str, ...]:
    imported: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.append(f"{'.' * node.level}{node.module}")
    return tuple(imported)


def _defined_or_referenced_names(node: ast.AST) -> tuple[str, ...]:
    if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
        return (node.name,)
    if isinstance(node, ast.Name):
        return (node.id,)
    if isinstance(node, ast.Attribute):
        return (node.attr,)
    if isinstance(node, ast.alias):
        return (node.name, node.asname or "")
    return ()


def _source_boundary_violations(relative: Path, text: str) -> list[str]:
    violations: list[str] = []
    lines = text.splitlines()
    removed_modules = {
        OLD_SERVING_MODULE,
        REMOVED_RETRIEVAL_MODULE,
        REMOVED_PROJECTION_MODULE,
    }
    if "serving_identity" in relative.name:
        violations.append(f"{relative}:old serving filename")
    if (
        "retrieval_v2" in relative.name or "retrieval-v2" in relative.name
    ) and not _immutable_v2_path(relative):
        violations.append(f"{relative}:current V2 filename")
    for line_number, line in enumerate(lines, 1):
        if "serving_identity" in line:
            violations.append(f"{relative}:{line_number}:old serving name")
        if any(name in line for name in REMOVED_PROJECTION_NAMES) and not _immutable_v2_path(
            relative
        ):
            violations.append(f"{relative}:{line_number}:removed projection name")
        if _contains_current_v2_name(line) and not _immutable_v2_path(relative):
            violations.append(f"{relative}:{line_number}:current V2 name")
    if relative.suffix in {".py", ".pyi"}:
        tree = ast.parse(text, filename=str(relative))
        static_environment = _python_static_environment(tree)
        violations.extend(
            f"{relative}:{name}"
            for name in _imports(tree)
            if name.lstrip(".") in removed_modules
            or name.lstrip(".").endswith(
                (
                    ".serving_identity",
                    ".retrieval_composition",
                    ".locator_projection_maintenance",
                )
            )
        )
        for node in ast.walk(tree):
            for name in _defined_or_referenced_names(node):
                if (
                    _old_retrieval_identifier(name) or _contains_current_v2_name(name)
                ) and not _immutable_v2_path(relative):
                    violations.append(f"{relative}:{name}")
            value = _static_python_string(node, static_environment)
            if value is not None:
                if any(module in value for module in removed_modules) and not _immutable_v2_path(
                    relative
                ):
                    violations.append(f"{relative}:dynamic old module string")
                if any(name in value for name in REMOVED_PROJECTION_NAMES) and not (
                    _immutable_v2_path(relative)
                ):
                    violations.append(f"{relative}:dynamic removed projection name")
                if _contains_current_v2_name(value) and not _immutable_v2_path(relative):
                    violations.append(f"{relative}:dynamic current V2 name")
    elif relative.suffix in {".cts", ".mts", ".ts", ".tsx"} or relative.name.endswith(
        (".d.cts", ".d.ts")
    ):
        for line_number, line in enumerate(lines, 1):
            violations.extend(
                f"{relative}:{line_number}:{name}"
                for name in re.findall(r"[A-Za-z_$][A-Za-z0-9_$]*", line)
                if (_old_retrieval_identifier(name) or _contains_current_v2_name(name))
                and not _immutable_v2_path(relative)
            )
        for value in _typescript_static_strings(text):
            line_number = text[: text.find(value)].count("\n") + 1 if value in text else 1
            if any(module in value for module in removed_modules) and not _immutable_v2_path(
                relative
            ):
                violations.append(f"{relative}:{line_number}:dynamic old module string")
            if any(name in value for name in REMOVED_PROJECTION_NAMES) and not (
                _immutable_v2_path(relative)
            ):
                violations.append(f"{relative}:{line_number}:dynamic removed projection name")
            if _contains_current_v2_name(value) and not _immutable_v2_path(relative):
                violations.append(f"{relative}:{line_number}:dynamic current V2 name")
    return violations


def _static_python_string(node: ast.AST, environment: dict[str, str]) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.Name):
        return environment.get(node.id)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left = _static_python_string(node.left, environment)
        right = _static_python_string(node.right, environment)
        return None if left is None or right is None else left + right
    if isinstance(node, ast.JoinedStr):
        parts: list[str] = []
        for value in node.values:
            if isinstance(value, ast.FormattedValue):
                part = _static_python_string(value.value, environment)
            else:
                part = _static_python_string(value, environment)
            if part is None:
                return None
            parts.append(part)
        return "".join(parts)
    return None


def _python_static_environment(tree: ast.AST) -> dict[str, str]:
    assignments: list[tuple[str, ast.AST]] = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else (node.target,)
            if node.value is not None:
                assignments.extend(
                    (target.id, node.value) for target in targets if isinstance(target, ast.Name)
                )
    assignment_counts: dict[str, int] = {}
    for name, _expression in assignments:
        assignment_counts[name] = assignment_counts.get(name, 0) + 1
    assignments = [item for item in assignments if assignment_counts[item[0]] == 1]
    environment: dict[str, str] = {}
    for _ in range(len(assignments) + 1):
        changed = False
        for name, expression in assignments:
            value = _static_python_string(expression, environment)
            if value is not None and environment.get(name) != value:
                environment[name] = value
                changed = True
        if not changed:
            break
    return environment


def _typescript_static_strings(source: str) -> tuple[str, ...]:
    assignment_pattern = re.compile(
        r"^\s*(?:const|let|var)\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*=\s*(.*?)\s*;?\s*$",
        re.MULTILINE,
    )
    discovered_assignments = tuple(assignment_pattern.findall(source))
    assignment_counts: dict[str, int] = {}
    for name, _expression in discovered_assignments:
        assignment_counts[name] = assignment_counts.get(name, 0) + 1
    assignments = tuple(item for item in discovered_assignments if assignment_counts[item[0]] == 1)
    environment: dict[str, str] = {}
    for _ in range(len(assignments) + 1):
        changed = False
        for name, expression in assignments:
            value = _typescript_static_expression(expression, environment)
            if value is not None and environment.get(name) != value:
                environment[name] = value
                changed = True
        if not changed:
            break
    values = set(environment.values())
    for match in re.finditer(r"`(?:[^`\\]|\\.)*`", source):
        value = _typescript_static_expression(match.group(0), environment)
        if value is not None:
            values.add(value)
    return tuple(sorted(values))


def _typescript_static_expression(expression: str, environment: dict[str, str]) -> str | None:
    expression = expression.strip().removesuffix(";").strip()
    parts = _split_typescript_addition(expression)
    if len(parts) > 1:
        values = tuple(_typescript_static_expression(part, environment) for part in parts)
        return None if any(value is None for value in values) else "".join(values)  # type: ignore[arg-type]
    if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", expression):
        return environment.get(expression)
    if len(expression) >= 2 and expression[0] == expression[-1] and expression[0] in "'\"":
        return bytes(expression[1:-1], "utf-8").decode("unicode_escape")
    if len(expression) >= 2 and expression[0] == expression[-1] == "`":
        body = expression[1:-1]
        cursor = 0
        values: list[str] = []
        for match in re.finditer(r"\$\{\s*([A-Za-z_$][A-Za-z0-9_$]*)\s*\}", body):
            values.append(body[cursor : match.start()])
            resolved = environment.get(match.group(1))
            if resolved is None:
                return None
            values.append(resolved)
            cursor = match.end()
        values.append(body[cursor:])
        return "".join(values)
    return None


def _split_typescript_addition(expression: str) -> tuple[str, ...]:
    parts: list[str] = []
    start = 0
    quote: str | None = None
    escaped = False
    for index, character in enumerate(expression):
        if escaped:
            escaped = False
            continue
        if character == "\\":
            escaped = True
            continue
        if quote is not None:
            if character == quote:
                quote = None
            continue
        if character in "'\"`":
            quote = character
        elif character == "+":
            parts.append(expression[start:index])
            start = index + 1
    parts.append(expression[start:])
    return tuple(part.strip() for part in parts)


def _current_text_files() -> tuple[Path, ...]:
    guard = Path(__file__).resolve()
    paths: set[Path] = set()
    for root in CURRENT_SOURCE_ROOTS:
        for directory, names, filenames in os.walk(root):
            relative_directory = Path(directory).relative_to(REPO_ROOT)
            names[:] = [
                name
                for name in names
                if relative_directory / name not in EXPLICIT_NON_SOURCE_DIRECTORIES
                and name not in EXPLICIT_NON_SOURCE_DIRECTORY_NAMES
            ]
            for filename in filenames:
                path = Path(directory) / filename
                if path != guard and (
                    path.suffix in TEXT_SUFFIXES or path.name.endswith((".d.cts", ".d.ts"))
                ):
                    paths.add(path)
    paths.update(
        path for path in (REPO_ROOT / "README.md", REPO_ROOT / "pyproject.toml") if path.exists()
    )
    return tuple(sorted(paths))


def _in_explicit_non_source_directory(path: Path) -> bool:
    relative = path.relative_to(REPO_ROOT)
    return any(
        prefix == parent or prefix in parent.parents
        for parent in relative.parents
        for prefix in EXPLICIT_NON_SOURCE_DIRECTORIES
    ) or any(name in EXPLICIT_NON_SOURCE_DIRECTORY_NAMES for name in relative.parts)


def _archive_member_relative(path: Path) -> Path:
    for root_name in ("packages", "docs", "examples", "scripts", "tests", "plugins", ".github"):
        if root_name in path.parts:
            return Path(*path.parts[path.parts.index(root_name) :])
    return path


def _immutable_v2_path(relative: Path) -> bool:
    return relative in IMMUTABLE_V2_PATHS or any(
        relative == prefix or prefix in relative.parents for prefix in IMMUTABLE_WIRE_PATH_PREFIXES
    )


def _contains_current_v2_name(value: str) -> bool:
    if "v2" not in value.lower():
        return False
    sanitized = value
    for pattern in IMMUTABLE_COMPATIBILITY_PATTERNS:
        sanitized = pattern.sub("", sanitized)
    return CURRENT_V2_NAME.search(sanitized) is not None


def _old_retrieval_identifier(value: str) -> bool:
    return (
        value not in IMMUTABLE_COMPATIBILITY_LITERALS
        and OLD_RETRIEVAL_IDENTIFIER.search(value) is not None
    )
