def test_all_chunk_delete_aggregate_families_are_version_fenced() -> None:
    class Vector:
        def __init__(self) -> None:
            self.points = {"chunk-a": 5}
            self.deleted: list[tuple[tuple[str, ...], int]] = []

        async def delete_chunks_if_version(
            self, chunk_ids: tuple[str, ...], *, canonical_version: int
        ) -> VectorWriteResult:
            self.deleted.append((chunk_ids, canonical_version))
            for chunk_id in chunk_ids:
                if self.points.get(chunk_id) == canonical_version:
                    del self.points[chunk_id]
            return VectorWriteResult.ok(len(chunk_ids))

    class Poison:
        def __getattr__(self, name: str) -> object:
            raise AssertionError(f"drained projection lane accessed: {name}")

    vector = Vector()
    container = SimpleNamespace(vector_index=vector)
    for name in REMOVED_PROJECTION_NAMES:
        setattr(container, name, Poison())
    process = ProjectionOutboxProcess(container)
    for aggregate_type in ("locator_chunk", "document", "thread"):
        for version in (4, 5):
            vector.points["chunk-a"] = 5
            payload: dict[str, object] = {"chunk_ids": ["chunk-a"]}
            aggregate_version = version if aggregate_type == "locator_chunk" else None
            if aggregate_type != "locator_chunk":
                payload["chunk_versions"] = [{"chunk_id": "chunk-a", "canonical_version": version}]
            asyncio.run(
                process.handle_vector_delete_chunks(
                    ClaimedOutboxJob(
                        id=len(vector.deleted) + 1,
                        event_type="vector.delete_chunks",
                        aggregate_id="aggregate-a",
                        aggregate_version=aggregate_version,
                        attempt_count=0,
                        workload_class="projection",
                        fairness_key=f"{aggregate_type}:aggregate-a",
                        payload_json=payload,
                        aggregate_type=aggregate_type,
                    )
                )
            )
            assert ("chunk-a" in vector.points) is (version == 4), aggregate_type

    assert vector.deleted == [(("chunk-a",), version) for _family in range(3) for version in (4, 5)]
    assert REMOVED_PROJECTION_NAMES.isdisjoint(Container.__annotations__)


